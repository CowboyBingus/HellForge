"""Export the weapons' melee (HD2R Editor's Melee rows on a weapon page) from HD2Runtime's melee authoring table.
Metadata only: names, field ids, record ids, offsets, ranges and the hit volumes' identity hashes; no game values.

Usage: py scripts/ExportMelee.py <HD2Runtime> mappings/melee.json native/mod-loader/melee_data.h

A weapon's melee attack (its bash) uses hit volumes: static records in game.dll's data (MeleeHitVolume, 248 bytes,
found by their RVA and checked by their type hash at +0), shared by every weapon whose attack uses them. Each volume
has its size, offset and repeat interval, and the damage row it deals (DamageInfo). A melee weapon's tuning (its
stamina cost) is its MeleeWeaponComponentData record.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from ExportStatsSchema import read_literal  # noqa: E402

VOLUME_SIZE = 248
NAMES = {'melee.volume_x': 'Hit volume X', 'melee.volume_y': 'Hit volume Y', 'melee.volume_z': 'Hit volume Z'}


def main(runtime, out, header):
    d = read_literal(Path(runtime) / 'domains' / 'melee_authoring.lua')
    if d.get('imageSize') != 0x4744000:
        raise SystemExit('melee authoring is for another game.dll')
    weapons, volumes = {}, {}
    for name, e in sorted(d['entries'].items()):
        zones, tuning = [], []
        for key in sorted(e['targets']):
            t = e['targets'][key]
            fields = []
            for fid in sorted(t['fields']):
                f = t['fields'][fid]
                b = f['backing']
                if f.get('editable') is False or b.get('storage') not in ('f32', 'u32', 'i32'):
                    continue
                field = {'id': fid, 'label': f.get('displayName') or NAMES.get(fid, fid), 'offset': b['offset'], 'storage': b['storage'],
                         'min': f.get('min'), 'max': f.get('max'), 'unit': f.get('unit')}
                if b.get('kind') == 'native' and b.get('component') == 'MeleeHitVolume':
                    field.update(kind='MeleeHitVolume', record=b['recordIndex'])
                elif b.get('kind') == 'settings' and b.get('settings') == 'damage' and isinstance(b.get('recordType'), int):
                    field.update(kind='DamageInfo', record=b['recordType'])
                elif b.get('kind') == 'component' and b.get('component'):
                    field.update(kind='component', component=b['component'], record=b['recordIndex'], resource=e['resource'])
                else:
                    continue
                fields.append(field)
            if not fields:
                continue
            if t.get('rva'):
                rva = t['rva']
                guard = bytes.fromhex(t['hex'][:8])
                volumes[rva] = int.from_bytes(guard, 'little')
                if len(t['hex']) // 2 != VOLUME_SIZE:
                    raise SystemExit('a hit volume of another size: %s %s' % (name, key))
                zones.append({'key': key, 'label': t.get('label') or key, 'rva': rva, 'consumers': len(t.get('consumers') or []), 'fields': fields})
            else:
                tuning.extend(fields)
        if zones or tuning:
            weapons[name] = {'resource': e['resource'], 'zones': zones, 'tuning': tuning}
    data = {'format': 1, 'build': '25480438', 'volumeSize': VOLUME_SIZE,
            'note': 'Weapon melee as HD2R Editor shows it (HD2Runtime 0.40.1 domains/melee_authoring; scripts/ExportMelee.py).',
            'components': d['components'], 'weapons': weapons}
    Path(out).write_text(json.dumps(data, indent=1, ensure_ascii=False) + '\n', encoding='utf-8', newline='\n')
    lines = ['/* Generated by scripts/ExportMelee.py from HD2Runtime 0.40.1 domains/melee_authoring.lua; do not edit.',
             ' * The melee hit volumes: static records in game.dll (build 25480438, SizeOfImage 0x4744000) by RVA, each',
             ' * checked by its type hash at +0. */',
             '#define MELEE_VOLUME_SIZE %du' % VOLUME_SIZE,
             'static const struct { uint32_t rva, hash; } kMeleeVolumes[] = {']
    lines += ['    {0x%Xu, 0x%08Xu},' % (rva, h) for rva, h in sorted(volumes.items())]
    lines += ['};', '']
    Path(header).write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print('%d weapons, %d hit volumes, %d fields' % (len(weapons), len(volumes),
          sum(len(z['fields']) for w in weapons.values() for z in w['zones']) + sum(len(w['tuning']) for w in weapons.values())))


if __name__ == '__main__':
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
