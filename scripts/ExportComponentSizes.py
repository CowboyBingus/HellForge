"""Export every entity component table's shape, for the mod loader's own-every-record copies (HfEntityDef.own_all: an
entity sharing no record with its base). Metadata only: slot counts, record counts and record sizes.

Usage: py scripts/ExportComponentSizes.py <HD2Runtime> <HD2Runtime-dev6> native/mod-loader/component_sizes.h

From HD2Runtime's component catalogue (research/component-catalogue-F5FEE03DCFDB.json, the 270 components of build
25480438's generated_entities.dl_bin): each table's index slots, records and record size. The catalogue names its tables;
HD2Runtime-dev6's scan of the same build's generated_entities.dl_bin (scripts/scan/tables.py) gives each table's
component index, so the loader knows a table's record size by its index (kComponentSizes). The shapes alone
(kComponentShapes) are what the loader falls back to: a table matched by its index slots and its size (index rows plus
whole records, padded to 16 bytes), and among several, the records its index rows reach. That guess sized the
WeaponLinker table wrongly (four 12-byte records, of which three are named: three 16-byte records fit too), so an
own_all copy of the Solo Silo's targeting remote had a garbled linker record (2026-10-18).
"""
import json
import sys
from pathlib import Path


def component_indices(dev6):
    sys.path.insert(0, str(Path(dev6) / 'scripts'))
    from scan.tables import pinned  # noqa: E402 (HD2Runtime-dev6: the pinned build's generated_entities.dl_bin)
    tables = pinned()
    return {index: tables.type_name(type_hash) for index, type_hash in tables._index_types().items()}


def main(runtime, dev6, out):
    catalogue = json.loads((Path(runtime) / 'research' / 'component-catalogue-F5FEE03DCFDB.json').read_text(encoding='utf-8'))
    sized = [c for c in catalogue['components'] if isinstance(c.get('recordSize'), int) and c['recordSize'] > 0 and isinstance(c.get('records'), int)]
    shapes = sorted({(c['indexCapacity'], c['records'], c['recordSize']) for c in sized})
    by_name = {c['component']: c for c in sized}
    sizes = sorted((index, by_name[name]['indexCapacity'], by_name[name]['records'], by_name[name]['recordSize'])
                   for index, name in component_indices(dev6).items() if name in by_name)
    lines = ['/* Generated by scripts/ExportComponentSizes.py from HD2Runtime 0.40.1 research/component-catalogue-F5FEE03DCFDB.json',
             " * and HD2Runtime-dev6's scan of the same build's generated_entities.dl_bin (the tables' component indices); do not",
             " * edit. Every entity component table's shape (build 25480438): index slots, records, record size; and by component",
             ' * index. */',
             'typedef struct ComponentShape { uint32_t slots, records, size; } ComponentShape;',
             'static const ComponentShape kComponentShapes[] = {']
    for i in range(0, len(shapes), 6):
        lines.append('    ' + ' '.join('{%du, %du, %du},' % shape for shape in shapes[i:i + 6]))
    lines += ['};',
              'typedef struct ComponentSize { uint16_t component; uint32_t slots, records, size; } ComponentSize;',
              'static const ComponentSize kComponentSizes[] = {']
    for i in range(0, len(sizes), 5):
        lines.append('    ' + ' '.join('{%d, %du, %du, %du},' % size for size in sizes[i:i + 5]))
    lines += ['};', '']
    Path(out).write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print('%d component table shapes, %d component indices sized' % (len(shapes), len(sizes)))


if __name__ == '__main__':
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
