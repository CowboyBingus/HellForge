"""Writes native/editor/ui_marks.h: the HD2R Editor's marker icons (edited, pending, mod, error; its assets/ui/ui_<name>@2x.png)
as 64 x 64 coverage masks (the brighter of the R and G mask layers, box-filtered from 512 x 512).
    py -3 scripts/ui_marks.py <HD2RuntimeEditor folder>"""
import struct
import sys
import zlib
from pathlib import Path

SIZE = 64


def read_png(path):
    data = Path(path).read_bytes()
    at, idat = 8, b''
    while at < len(data):
        n, kind = struct.unpack('>I4s', data[at:at + 8])
        body = data[at + 8:at + 8 + n]
        if kind == b'IHDR':
            w, h, depth, colour = struct.unpack('>IIBB', body[:10])
            assert depth == 8 and colour in (2, 6), (path, depth, colour)
            channels = 3 if colour == 2 else 4
        elif kind == b'IDAT':
            idat += body
        at += 12 + n
    raw = zlib.decompress(idat)
    stride = w * channels
    rows, prev, at = [], bytearray(stride), 0
    for _ in range(h):
        f, line = raw[at], bytearray(raw[at + 1:at + 1 + stride])
        at += 1 + stride
        for i in range(stride):
            a = line[i - channels] if i >= channels else 0
            b, c = prev[i], prev[i - channels] if i >= channels else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c; pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(line)
        prev = line
    return w, h, channels, rows


def mask(path):
    w, h, ch, rows = read_png(path)
    step = w // SIZE
    out = []
    for y in range(SIZE):
        for x in range(SIZE):
            total = 0
            for yy in range(y * step, (y + 1) * step):
                row = rows[yy]
                for xx in range(x * step, (x + 1) * step):
                    total += max(row[xx * ch], row[xx * ch + 1])
            out.append(total // (step * step))
    return out


def main():
    source = Path(sys.argv[1]) / 'assets' / 'ui'
    lines = ['/* Generated by scripts/ui_marks.py from the HD2R Editor\'s marker icons (assets/ui/ui_<name>@2x.png): %d x %d' % (SIZE, SIZE),
             ' * coverage masks. Do not edit. */',
             '#pragma once', '#define UI_MARK_SIZE %d' % SIZE,
             'enum { UI_MARK_EDITED, UI_MARK_PENDING, UI_MARK_MOD, UI_MARK_ERROR, UI_MARK_COUNT };',
             'static const unsigned char kUiMarks[UI_MARK_COUNT][UI_MARK_SIZE * UI_MARK_SIZE] = {']
    for name in ('edited', 'pending', 'mod', 'error'):
        values = mask(source / ('ui_%s@2x.png' % name))
        lines.append('    { /* %s */' % name)
        for i in range(0, len(values), 32):
            lines.append('        ' + ','.join(str(v) for v in values[i:i + 32]) + ',')
        lines.append('    },')
    lines.append('};')
    Path(__file__).resolve().parents[1].joinpath('native', 'editor', 'ui_marks.h').write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print('wrote native/editor/ui_marks.h')


if __name__ == '__main__':
    main()
