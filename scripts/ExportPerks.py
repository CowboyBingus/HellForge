"""Export the armor perks' values (HD2R Editor's Armor perks category) from HD2Runtime's armor perk table.
Metadata only: passive ids, modifier keys and types, stat ids, labels, ranges and defaults as labels; code pins.

Usage: py scripts/ExportPerks.py <HD2Runtime> mappings/armor-perks.json native/mod-loader/perk_data.h

A perk's values live in the customization manager's passive rows (game.dll [+0x33264F8], the manager passives.c
finds): manager+0x20 {pointer to the rows' pointers, u32 count 32, 0}, manager+0x30 u32[42] passive id -> slot; a row
(0x34 bytes): id +0, name id +4, icon u64 +8, modifiers {pointer, u32 count, 0} +0x10, stats {pointer, u32 count, 0}
+0x20, package u32 +0x30; a modifier 16 bytes {key u32, type u32, value f32 +8}, a stat 12 bytes {stat u32, add f32 +4,
mul f32 +8}. HellForge names an entry as a settings row: PassiveModifier / PassiveStat, id = passive * 16 + index.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from ExportReferences import read_table  # noqa: E402

TYPES = {'Set': 0, 'Add': 1, 'Multiply': 2, 'Time': 3}


def main(runtime, out_json, out_header):
    d = read_table(Path(runtime) / 'domains' / 'armor_perks.lua')
    m = d['manager']
    if m['globalRva'] != 0x33264F8 or m['passives'] != 0x20 or m['passiveIndex'] != 0x30 or m['passiveIds'] != 42:
        raise ValueError('the customization manager is not the reviewed one')
    perks = []
    for e in sorted(d['entries'], key=lambda e: e['id']):
        fields = {}
        for f in e['fields']:
            b = f['backing']
            part, index = b['part'], b['index']
            kind = 'PassiveModifier' if part == 'modifier' else 'PassiveStat'
            stride = 16 if part == 'modifier' else 12
            offset = b['offset'] - index * stride
            if not (0 <= offset < stride):
                raise ValueError(f'perk {e["id"]} {f["semanticFieldId"]}: offset {b["offset"]} is not in entry {index}')
            fields[f['semanticFieldId']] = {
                'label': f['label'], 'section': f['section'], 'kind': kind, 'record': e['id'] * 16 + index, 'offset': offset,
                'storage': b['storage'], 'min': f.get('min'), 'max': f.get('max'), 'unit': f.get('unit'),
                'base': f.get('currentDefault'), 'whole': f.get('unit') == 'count' or f.get('type') == 'integer',
                'note': f.get('lifecycle'), 'hd2r': f'ap|{e["id"]}|{f["semanticFieldId"]}',
            }
        perks.append({'id': e['id'], 'name': e['name'], 'description': e['description'], 'fields': fields})
    data = {'format': 1, 'build': '25480438',
            'note': 'Armor perk values (HD2Runtime 0.40.1 domains/armor_perks; scripts/ExportPerks.py). Shared by every '
                    'wearer of the perk; no perk value edit is gameplay-tested in HD2Runtime.',
            'perks': perks}
    Path(out_json).write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n', encoding='utf-8', newline='\n')

    h = ['/* Generated by scripts/ExportPerks.py from HD2Runtime 0.40.1 domains/armor_perks for game build 25480438; do not',
         ' * edit. Passive identities, their modifier keys and types and stat ids, and the code pins. Included by perks.c. */', '',
         f'#define PERK_MANAGER 0x{m["globalRva"]:X}u', f'#define PERK_PASSIVES 0x{m["passives"]:X}u',
         f'#define PERK_INDEX 0x{m["passiveIndex"]:X}u', f'#define PERK_IDS {m["passiveIds"]}u', f'#define PERK_COUNT {len(d["entries"])}u', '',
         'typedef struct PerkPin { uint32_t rva; uint8_t size; uint8_t bytes[16]; } PerkPin;', 'static const PerkPin kPerkPins[] = {']
    for p in d['pins']:
        b = bytes.fromhex(p['hex'])
        if len(b) > 16:
            raise ValueError('a pin longer than 16 bytes')
        h.append(f'    {{0x{p["rva"]:X}u, {len(b)}, {{{", ".join(f"0x{x:02x}" for x in b)}}}}}, /* {p["label"].replace("*/", "")} */')
    h += ['};', '',
          'typedef struct PerkEntry { uint32_t id, nameId; uint64_t icon; uint32_t package; uint8_t modifiers, stats; uint16_t first; } PerkEntry;',
          '/* modifiers: {key, type} pairs; stats: stat ids; an entry\'s start in kPerkItems */']
    items, entries = [], []
    for e in sorted(d['entries'], key=lambda e: e['id']):
        first = len(items)
        for mod in e['modifiers']:
            items.append((int(mod['key'], 16), TYPES[mod['type']]))
        for st in e['stats']:
            items.append((st['stat'], 0xFFFFFFFF))
        entries.append(f'    {{{e["id"]}u, 0x{e["nameId"]}u, 0x{e["icon"]}ull, 0x{e["package"]}u, {len(e["modifiers"])}, {len(e["stats"])}, {first}}}, /* {e["name"]} */')
    h.append('static const uint32_t kPerkItems[][2] = {')
    h += [f'    {{0x{k:08X}u, 0x{t:X}u}},' for k, t in items]
    h += ['};', 'static const PerkEntry kPerkEntries[] = {'] + entries + ['};']
    Path(out_header).write_text('\n'.join(h) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(perks)} perks, {sum(len(p["fields"]) for p in perks)} fields, {len(d["pins"])} pins')


if __name__ == '__main__':
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
